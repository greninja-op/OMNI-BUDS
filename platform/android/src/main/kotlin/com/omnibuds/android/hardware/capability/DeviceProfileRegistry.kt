    /**
     * Resolves a known profile matching [deviceName].
     */
    fun findProfile(deviceName: String?): Profile? {
        val name = (deviceName ?: "").lowercase().trim()
        return PROFILES.firstOrNull { name.contains(it.modelKey) }
    }
